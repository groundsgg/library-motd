import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const output = resolve(root, "assets/ui/panorama-demo");
const palettes = {
  evergreen: {
    sky: ["#385b75", "#9dbbb0"],
    far: "#557d7a",
    near: "#31564c",
    ground: "#203e32",
    light: "#f1d48b",
  },
  dusk: {
    sky: ["#403c68", "#d28465"],
    far: "#796077",
    near: "#4e445d",
    ground: "#302e42",
    light: "#ffe0a3",
  },
};

export function panoramaFaceSvg(theme, face) {
  const p = palettes[theme];
  if (!p || !Number.isInteger(face) || face < 0 || face > 5)
    throw new TypeError("Unknown demo panorama face");
  const shift = [0, 10, -8, 16, -13, 5][face];
  const stars =
    theme === "dusk"
      ? `<g fill="${p.light}"><path d="M42 38h4v4h-4zM85 66h3v3h-3zM202 42h4v4h-4zM177 82h3v3h-3zM129 31h3v3h-3z"/></g>`
      : "";
  const sun =
    face === 1 || face === 4
      ? `<path fill="${p.light}" d="M179 47h18v18h-18z"/>`
      : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">
<defs><linearGradient id="sky" x2="0" y2="1"><stop stop-color="${p.sky[0]}"/><stop offset="1" stop-color="${p.sky[1]}"/></linearGradient><linearGradient id="ground" x2="0" y2="1"><stop stop-color="${p.near}"/><stop offset="1" stop-color="${p.ground}"/></linearGradient></defs>
<path fill="url(#sky)" d="M0 0h256v256H0z"/>
${stars}${sun}
<path fill="${p.far}" d="M0 ${148 + shift}l28-30 20 17 27-41 29 39 30-26 24 19 27-36 31 26 40-28v96H0z"/>
<path fill="${p.near}" d="M0 ${171 - shift}l25-20 20 13 31-32 27 20 26-27 31 25 22-12 32 27 23-16 19 10v97H0z"/>
<path fill="url(#ground)" d="M0 194h256v62H0z"/>
<path fill="${p.ground}" d="M18 177h8v25h-8zM13 168h18v12H13zM78 168h8v29h-8zM72 157h20v15H72zM214 173h8v27h-8zM208 162h20v14h-20z"/>
<path fill="#c4d2a0" opacity=".76" d="M0 215h35v4H0zM103 232h46v4h-46zM188 210h30v4h-30z"/>
<path fill="#182d30" opacity=".32" d="M0 246h256v10H0z"/>
</svg>`;
}

async function build() {
  await mkdir(output, { recursive: true });
  const profiles = {};
  for (const [profile, theme] of [
    ["java-26.3", "evergreen"],
    ["java-1.21.1", "dusk"],
  ]) {
    const faces = [];
    for (let face = 0; face < 6; face++) {
      const name = `${theme}-${face}.svg`;
      const bytes = Buffer.from(panoramaFaceSvg(theme, face) + "\n");
      await writeFile(resolve(output, name), bytes);
      faces.push({
        file: name,
        sha256: createHash("sha256").update(bytes).digest("hex"),
      });
    }
    profiles[profile] = { theme, faces };
  }
  await writeFile(
    resolve(output, "manifest.json"),
    JSON.stringify(
      {
        license: "CC0-1.0",
        source:
          "Original Grounds demo artwork generated by tools/build-panorama-demo.mjs; no game files or textures.",
        profiles,
      },
      null,
      2,
    ) + "\n",
  );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await build();
