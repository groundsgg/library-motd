// Maintainer operation: derive cells from independently recreated OFL outlines.
// No Minecraft client, texture, native reference image or runtime dependency.
import { openSync } from "fontkit";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const faces = [];
for (const suffix of ["", "-Bold"]) {
  const font = openSync(
    fileURLToPath(
      new URL(`assets/java-1.21.1/GroundsPixel${suffix}.otf`, root),
    ),
  );
  if (font.unitsPerEm !== 18)
    throw Error("Unexpected outline coordinate system");
  const glyphs = {};
  for (const code of font.characterSet) {
    const glyph = font.glyphForCodePoint(code);
    // U+FFFF is a vector missing-glyph symbol, not a two-unit pixel outline.
    // Preserve its browser fallback instead of quantizing a different shape.
    if (
      glyph.path.commands.some(({ args }) =>
        args.some((value, index) => value % 2 !== (index % 2 === 0 ? 1 : 0)),
      )
    )
      continue;
    if (
      glyph.path.commands.length &&
      (glyph.bbox.minX < 1 ||
        glyph.bbox.maxX > 21 ||
        glyph.bbox.minY < -4 ||
        glyph.bbox.maxY > 20)
    )
      throw Error(`Glyph outside pixel-cell bounds: ${code}`);
    const edges = [];
    let point, start;
    for (const { command, args } of glyph.path.commands) {
      if (command === "moveTo") point = start = args;
      else if (command === "lineTo") {
        edges.push([point, args]);
        point = args;
      } else if (command === "closePath") {
        edges.push([point, start]);
        point = start;
      } else throw Error(`Non-pixel outline: ${command}`);
    }
    // Each cell is two font units, with a one-unit left bearing and baseline 16.
    // Include the umlaut/accent row above the ordinary line and descenders below.
    const rows = [];
    for (let y = -2; y < 10; y++) {
      let bits = 0;
      for (let x = 0; x < 10; x++) {
        const px = 2 * x + 2,
          py = 15 - 2 * y;
        let winding = 0;
        for (const [[ax, ay], [bx, by]] of edges) {
          const side = (bx - ax) * (py - ay) - (px - ax) * (by - ay);
          if (ay <= py && by > py && side > 0) winding++;
          if (ay > py && by <= py && side < 0) winding--;
        }
        if (winding) bits |= 1 << x;
      }
      rows.push(bits);
    }
    glyphs[String.fromCodePoint(code)] = rows;
  }
  faces.push(glyphs);
}
const output = `// Generated by tools/build-pixel-font.mjs from GroundsPixel OFL outlines.
// Copyright Idrees Hassan; SIL OFL 1.1. See assets/java-1.21.1/OFL.txt and provenance.json.
export const pixelTop = -2;
export const pixelColumns = 10;
export const pixelFaces: readonly Readonly<Record<string, readonly number[]>>[] = ${JSON.stringify(faces, null, 2)};\n`;
const target = new URL("src/dom/font/pixels.ts", root);
// Use the project's pinned formatter so --check compares the committed artifact.
const { format } = await import("prettier");
const formatted = await format(output, { parser: "typescript", tabWidth: 2 });
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== formatted)
    throw Error("Pixel font is stale");
} else writeFileSync(target, formatted);
